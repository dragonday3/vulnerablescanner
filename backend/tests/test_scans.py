def test_get_scan_and_status_expose_error_message_for_failed_scan(
    client: TestClient, db: Session
) -> None:
    """Finding 4: `Scan.error_message` already exists on the model (Task 6)
    but was never exposed via the API - a caller polling a failed scan had
    no way to learn why. Both `GET /scans/{id}` and `GET /scans/{id}/status`
    must surface it once populated.
    """
    ctx = _create_authorized_target(client)
    scan = _create_scan(client, ctx)

    # Bypass the worker and flip the scan straight to FAILED with an
    # error_message, mirroring the DB-bypass pattern already used above for
    # authorization revocation - this test only cares about API exposure of
    # an already-populated column, not the orchestration logic that sets it
    # (covered separately in test_scan_orchestration.py).
    scan_row = db.get(Scan, uuid.UUID(scan["id"]))
    assert scan_row is not None
    scan_row.status = ScanStatus.FAILED
    scan_row.error_message = "nmap exited with status 1 scanning '10.0.0.10': boom"
    db.commit()

    get_resp = client.get(f"/api/v1/scans/{scan['id']}")
    assert get_resp.status_code == 200
    assert get_resp.json()["error_message"] == scan_row.error_message

    status_resp = client.get(f"/api/v1/scans/{scan['id']}/status")
    assert status_resp.status_code == 200
    assert status_resp.json()["error_message"] == scan_row.error_message


